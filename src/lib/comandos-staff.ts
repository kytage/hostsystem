/**
 * Pode ser usado por um Admin de nível `nivel` (1 = mais alto)? "Admin" sem número vale para
 * qualquer nível; "Admin ≤N" vale do nível 1 até o N.
 */
export function adminPodeUsar(c: ComandoStaff, nivel: number): boolean {
  return c.quem.some((q) => {
    const m = /^Admin(?:\s*≤\s*(\d+))?$/.exec(q.trim());
    if (!m) return false;
    return !m[1] || nivel <= Number(m[1]);
  });
}

